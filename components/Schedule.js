'use client';
import { useLang } from './LanguageProvider';
import { useState } from 'react';
import { AlertCircle } from 'lucide-react';
import ParticipantPicker from './ParticipantPicker';
import { supabase } from '../lib/supabaseClient';
import { findCollision, isOverlapErr, overlapMsg } from '../lib/helpers';

const input = 'w-full px-4 py-2.5 rounded-xl border border-slate-200 focus:outline-none focus:ring-2 focus:ring-fuboru-red text-sm';
const label = 'block text-xs font-semibold text-slate-700 uppercase tracking-wider mb-2';
const EMPTY = { name: '', date: '', room: '', start: '', end: '' };

export default function Schedule({ rooms, employees, notify, onCancel, onCreated }) {
  const { t } = useLang();
  const [f, setF] = useState(EMPTY);
  const [people, setPeople] = useState([]);
  const [error, setError] = useState('');
  const [busy, setBusy] = useState(false);
  const set = (k) => (e) => setF({ ...f, [k]: e.target.value });

  async function submit(e) {
    e.preventDefault();
    setError('');
    if (f.start >= f.end) return setError(t('err.endBeforeStart'));
    setBusy(true);
    try {
      const clash = await findCollision(f.room, f.date, f.start, f.end);
      if (clash) return setError(overlapMsg(f.room, clash, t));

      // "Meeting ID" is generated by the database trigger
      const { data: m, error: err } = await supabase.from('meeting')
        .insert({ 'Nama Meeting': f.name.trim(), Tanggal: f.date, Mulai: f.start, Selesai: f.end, Ruangan: f.room, Status: 'Planned' })
        .select().single();
      if (err) return setError(isOverlapErr(err) ? t('err.bookedGeneric') : err.message);

      if (people.length) {
        const { error: pErr } = await supabase.from('participant')
          .insert(people.map((n) => ({ 'Meeting ID': m['Meeting ID'], 'Nama Peserta': n, 'Jumlah Tap': 0 })));
        if (pErr) notify(t('msg.partFailed', { id: m['Meeting ID'], err: pErr.message }));
      }
      notify(t('msg.scheduled', { id: m['Meeting ID'] }), true);
      setF(EMPTY); setPeople([]);
      await onCreated();
    } catch (err) { setError(err.message); }
    finally { setBusy(false); }
  }

  return (
    <section className="p-4 sm:p-6 md:p-8 max-w-4xl w-full mx-auto space-y-6">
      <div className="border-b border-slate-200 pb-4">
        <h1 className="text-2xl font-bold text-slate-900">{t('sch.title')}</h1>
        <p className="text-sm text-slate-500">{t('sch.sub')}</p>
      </div>
      <form onSubmit={submit} className="bg-white rounded-2xl border border-slate-200/80 shadow-sm p-4 sm:p-6 space-y-6">
        <div className="grid grid-cols-1 md:grid-cols-2 gap-6">
          <div className="md:col-span-2">
            <label className={label}>{t('f.name')} <span className="text-rose-500">*</span></label>
            <input required value={f.name} onChange={set('name')} placeholder={t('f.namePh')} className={input} />
          </div>
          <div>
            <label className={label}>{t('f.date')} <span className="text-rose-500">*</span></label>
            <input type="date" required value={f.date} onChange={set('date')} className={input} />
          </div>
          <div>
            <label className={label}>{t('f.room')} <span className="text-rose-500">*</span></label>
            <select required value={f.room} onChange={set('room')} className={`${input} bg-white`}>
              <option value="">{t('f.selectRoom')}</option>
              {rooms.map((r) => <option key={r['Room ID']} value={r['Nama Ruangan']}>{r['Nama Ruangan']}</option>)}
            </select>
          </div>
          <div>
            <label className={label}>{t('f.start')} <span className="text-rose-500">*</span></label>
            <input type="time" required value={f.start} onChange={set('start')} className={input} />
          </div>
          <div>
            <label className={label}>{t('f.end')} <span className="text-rose-500">*</span></label>
            <input type="time" required value={f.end} onChange={set('end')} className={input} />
          </div>
        </div>

        <div className="space-y-3">
          <label className={label}>{t('sch.participants')}</label>
          <ParticipantPicker employees={employees} selected={people} onChange={setPeople} />
        </div>

        {error && (
          <div className="p-4 rounded-xl bg-rose-50 border border-rose-200 text-rose-700 text-xs font-medium flex items-center space-x-2">
            <AlertCircle className="w-4 h-4 shrink-0" /><span>{error}</span>
          </div>
        )}

        <div className="flex items-center justify-end space-x-3 pt-4 border-t border-slate-100">
          <button type="button" onClick={onCancel} className="px-5 py-2.5 rounded-xl border border-slate-200 text-xs font-semibold text-slate-600 hover:bg-slate-50">{t('common.cancel')}</button>
          <button type="submit" disabled={busy} className="px-6 py-2.5 rounded-xl bg-fuboru-red hover:bg-fuboru-redHover disabled:opacity-60 text-white text-xs font-semibold shadow-sm transition">
            {busy ? t('sch.submitting') : t('sch.submit')}
          </button>
        </div>
      </form>
    </section>
  );
}
